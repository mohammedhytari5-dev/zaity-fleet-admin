CREATE TABLE IF NOT EXISTS `client_portal_requests` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `request_type` VARCHAR(100) NOT NULL,
  `client_type` VARCHAR(50) NOT NULL DEFAULT 'عميل جديد',
  `company_name` VARCHAR(255) NOT NULL,
  `contact_person` VARCHAR(160) NOT NULL,
  `phone` VARCHAR(40) NOT NULL,
  `email` VARCHAR(160) DEFAULT NULL,
  `city` VARCHAR(100) NOT NULL,
  `bus_type` VARCHAR(100) DEFAULT NULL,
  `buses_count` INT NOT NULL DEFAULT 1,
  `duration` VARCHAR(100) DEFAULT NULL,
  `start_date` VARCHAR(30) DEFAULT NULL,
  `work_nature` VARCHAR(255) DEFAULT NULL,
  `daily_estimated_km` INT DEFAULT NULL,
  `with_driver` INT NOT NULL DEFAULT 1,
  `with_fuel` INT NOT NULL DEFAULT 1,
  `current_contract_no` VARCHAR(100) DEFAULT NULL,
  `bus_plate_number` VARCHAR(40) DEFAULT NULL,
  `driver_name` VARCHAR(160) DEFAULT NULL,
  `details` TEXT DEFAULT NULL,
  `status` VARCHAR(50) NOT NULL DEFAULT 'جديد',
  `assigned_to` VARCHAR(160) DEFAULT NULL,
  `response_notes` TEXT DEFAULT NULL,
  `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  `updated_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP NOT NULL
);
